import { existsSync, readFileSync } from 'node:fs'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { NOTIFY_SESSION_CVARS } from './playback-channel/protocol'
import {
  STAGE_CVAR_NAMES,
  createCvarRestore,
  nodeCvarRestoreFs,
  readArchivedCvar,
  sessionConfigPath,
} from './session-cvar-restore'
import { limitsFor } from '@shared/config/syntax/engine-limits'

/** Story 170 D3: the stage cvars' snapshot/restore, against real files in a temp dir. */

let tmp: string
let configPath: string
let pendingPath: string

beforeEach(async () => {
  tmp = await mkdtemp(join(tmpdir(), 'cvar-restore-'))
  await mkdir(join(tmp, 'baseq2'))
  configPath = join(tmp, 'baseq2', 'q2config.cfg')
  pendingPath = join(tmp, 'userData', 'pending.json')
})

afterEach(async () => {
  await rm(tmp, { recursive: true, force: true })
})

const restorer = () => createCvarRestore({ names: STAGE_CVAR_NAMES, pendingPath })
const bytes = (text: string): Buffer => Buffer.from(text, 'latin1')
const readBytes = (): Promise<Buffer> => readFile(configPath)

/** The pid of each pending record, oldest first; a single record is stored bare. */
function pendingPids(): Array<number | undefined> {
  const raw = JSON.parse(readFileSync(pendingPath, 'utf8')) as { pid?: number } | { pid?: number }[]
  return (Array.isArray(raw) ? raw : [raw]).map((record) => record.pid)
}

/** A next launcher start that sees `alive` running and collects its scheduled retries. */
function waitingRestorer(alive: number[]) {
  const running = new Set(alive)
  const retries: Array<() => void> = []
  const next = createCvarRestore({
    names: STAGE_CVAR_NAMES,
    pendingPath,
    isAlive: (pid) => running.has(pid),
    scheduleRetry: (run) => {
      retries.push(run)
      return () => undefined
    },
  })
  return { next, running, retries }
}

describe('session cvar restore', () => {
  it('restores vid_fullscreen and vid_geometry lines byte-exact', async () => {
    const before =
      '// generated by q2pro\r\nset name "Pl\xe4yer"\r\nset vid_fullscreen "1"\r\n  seta vid_geometry "1920x1080+0+0"\r\nset gl_swapinterval "1"\r\n'
    await writeFile(configPath, bytes(before))
    const cvars = restorer()
    await cvars.snapshot(configPath)
    expect(existsSync(pendingPath)).toBe(true)
    // What the engine writes on exit after a stage session.
    await writeFile(
      configPath,
      bytes(
        '// generated by q2pro\r\nset name "Pl\xe4yer"\r\nset vid_fullscreen "0"\r\nset vid_geometry "640x360+10+20"\r\nset gl_swapinterval "1"\r\n',
      ),
    )
    await cvars.restore()
    expect((await readBytes()).equals(bytes(before))).toBe(true)
    expect(existsSync(pendingPath)).toBe(false)
  })

  it('removes a cvar that was absent before', async () => {
    const before = 'set name "a"\nset vid_fullscreen "1"\n'
    await writeFile(configPath, bytes(before))
    const cvars = restorer()
    await cvars.snapshot(configPath)
    await writeFile(
      configPath,
      bytes('set name "a"\nset vid_fullscreen "0"\nset vid_geometry "640x360+10+20"\n'),
    )
    await cvars.restore()
    expect((await readBytes()).toString('latin1')).toBe(before)
  })

  it('removes both when the file did not exist before the session', async () => {
    const cvars = restorer()
    await cvars.snapshot(configPath)
    await writeFile(
      configPath,
      bytes('set vid_fullscreen "0"\r\nset name "a"\r\nset vid_geometry "640x360+10+20"'),
    )
    await cvars.restore()
    expect((await readBytes()).toString('latin1')).toBe('set name "a"\r\n')
  })

  it("keeps the user's in-session changes", async () => {
    await writeFile(
      configPath,
      bytes(
        'set sensitivity "3"\r\nset vid_fullscreen "1"\r\nset vid_geometry "1920x1080+0+0"\r\n',
      ),
    )
    const cvars = restorer()
    await cvars.snapshot(configPath)
    await writeFile(
      configPath,
      bytes(
        'set sensitivity "5"\r\nset vid_fullscreen "0"\r\nset vid_geometry "640x360+10+20"\r\nset cl_new "1"\r\n',
      ),
    )
    await cvars.restore()
    expect((await readBytes()).toString('latin1')).toBe(
      'set sensitivity "5"\r\nset vid_fullscreen "1"\r\nset vid_geometry "1920x1080+0+0"\r\nset cl_new "1"\r\n',
    )
  })

  it("puts back a line the engine dropped, with the file's own line ending", async () => {
    await writeFile(configPath, bytes('set a "1"\r\nset vid_fullscreen "1"\r\n'))
    const cvars = restorer()
    await cvars.snapshot(configPath)
    await writeFile(configPath, bytes('set a "2"\r\nset b "3"'))
    await cvars.restore()
    expect((await readBytes()).toString('latin1')).toBe(
      'set a "2"\r\nset b "3"\r\nset vid_fullscreen "1"\r\n',
    )
  })

  it('a missing file does nothing', async () => {
    await writeFile(configPath, bytes('set vid_fullscreen "1"\n'))
    const cvars = restorer()
    await cvars.snapshot(configPath)
    await rm(configPath)
    await cvars.restore()
    expect(existsSync(configPath)).toBe(false)
    expect(existsSync(pendingPath)).toBe(false)
  })

  it('applies a pending snapshot at start', async () => {
    const before = 'set vid_fullscreen "1"\r\nset name "a"\r\n'
    await writeFile(configPath, bytes(before))
    // A launcher that crashed mid-session: snapshot taken, restore never ran.
    await restorer().snapshot(configPath)
    await writeFile(
      configPath,
      bytes('set vid_fullscreen "0"\r\nset name "b"\r\nset vid_geometry "640x360+10+20"\r\n'),
    )

    const next = restorer()
    await next.applyPending()
    expect((await readBytes()).toString('latin1')).toBe(
      'set vid_fullscreen "1"\r\nset name "b"\r\n',
    )
    expect(existsSync(pendingPath)).toBe(false)
    // Once only: nothing is pending any more.
    await writeFile(configPath, bytes('set vid_fullscreen "0"\r\n'))
    await next.applyPending()
    expect((await readBytes()).toString('latin1')).toBe('set vid_fullscreen "0"\r\n')
  })

  it('a pending restore waits while the recorded game is still running', async () => {
    await writeFile(configPath, bytes('set vid_fullscreen "1"\nset name "a"\n'))
    // A launcher quit with the game left running: snapshot and pid persisted, restore never ran.
    const quitting = restorer()
    await quitting.snapshot(configPath)
    await quitting.recordPid(4242)
    const stage = 'set vid_fullscreen "0"\nset name "a"\nset vid_geometry "640x360+10+20"\n'
    await writeFile(configPath, bytes(stage))

    const running = new Set([4242])
    const retries: Array<() => void> = []
    const waitingFor: number[] = []
    const next = createCvarRestore({
      names: STAGE_CVAR_NAMES,
      pendingPath,
      onWaiting: (pid) => waitingFor.push(pid),
      isAlive: (pid) => running.has(pid),
      scheduleRetry: (run) => {
        retries.push(run)
        return () => undefined
      },
    })
    await next.applyPending()
    expect((await readBytes()).toString('latin1')).toBe(stage)
    expect(existsSync(pendingPath)).toBe(true)
    expect(retries).toHaveLength(1)
    expect(waitingFor).toEqual([4242])

    running.delete(4242)
    retries[0]()
    // Serialised behind the retry's own pass, so this resolves once that pass has finished.
    await next.restore()
    expect((await readBytes()).toString('latin1')).toBe('set vid_fullscreen "1"\nset name "a"\n')
    expect(existsSync(pendingPath)).toBe(false)
    expect(retries).toHaveLength(1)
  })

  it('a pending restore without a pid restores at once', async () => {
    await mkdir(join(tmp, 'userData'), { recursive: true })
    await writeFile(
      pendingPath,
      JSON.stringify({
        configPath,
        lines: { vid_fullscreen: 'set vid_fullscreen "1"', vid_geometry: null },
      }),
    )
    await writeFile(configPath, bytes('set vid_fullscreen "0"\nset vid_geometry "640x360+10+20"\n'))
    const next = createCvarRestore({
      names: STAGE_CVAR_NAMES,
      pendingPath,
      isAlive: () => true,
      scheduleRetry: () => {
        throw new Error('a record without a pid never waits')
      },
    })
    await next.applyPending()
    expect((await readBytes()).toString('latin1')).toBe('set vid_fullscreen "1"\n')
    expect(existsSync(pendingPath)).toBe(false)
  })

  it("a new session started while a previous launcher's game still runs leaves that game's record waiting for its exit", async () => {
    const user = 'set vid_fullscreen "1"\nset name "a"\n'
    const stage = 'set vid_fullscreen "0"\nset name "a"\nset vid_geometry "640x360+10+20"\n'
    await writeFile(configPath, bytes(user))
    const quitting = restorer()
    await quitting.snapshot(configPath)
    await quitting.recordPid(4242)

    const { next, running, retries } = waitingRestorer([4242])
    await next.applyPending()
    await next.snapshot(configPath)
    running.add(5151)
    await next.recordPid(5151)
    // Each session's record carries its own game's pid.
    expect(pendingPids()).toEqual([4242, 5151])

    // The new session ends first; the old game is still running and archives the stage on exit.
    await writeFile(configPath, bytes(stage))
    running.delete(5151)
    await next.restore()
    expect((await readBytes()).toString('latin1')).toBe(user)
    expect(pendingPids()).toEqual([4242])

    await writeFile(configPath, bytes(stage))
    running.delete(4242)
    retries.at(-1)?.()
    // Serialised behind the retry's own pass.
    await next.restore()
    expect((await readBytes()).toString('latin1')).toBe(user)
    expect(existsSync(pendingPath)).toBe(false)
  })

  it('a session adopting a record its failed repair left behind records its own pid', async () => {
    await writeFile(configPath, bytes('set vid_fullscreen "1"\n'))
    const quitting = restorer()
    await quitting.snapshot(configPath)
    await quitting.recordPid(4242)
    await writeFile(configPath, bytes('set vid_fullscreen "0"\n'))

    const fs = {
      ...nodeCvarRestoreFs,
      rename: async (from: string, to: string) => {
        if (to === configPath) throw Object.assign(new Error('busy'), { code: 'EBUSY' })
        return nodeCvarRestoreFs.rename(from, to)
      },
    }
    // The old game is gone, but the config cannot be repaired before the next play.
    const next = createCvarRestore({
      names: STAGE_CVAR_NAMES,
      pendingPath,
      fs,
      isAlive: () => false,
    })
    await next.snapshot(configPath)
    await next.recordPid(5151)
    expect(pendingPids()).toEqual([5151])
    expect(next.originalsLine()).toBe('set vid_fullscreen "1"; reset vid_geometry')
  })

  it('a pending retry never restores the record of the session that is starting', async () => {
    await writeFile(configPath, bytes('set vid_fullscreen "1"\n'))
    const quitting = restorer()
    await quitting.snapshot(configPath)
    await quitting.recordPid(4242)

    const { next, running, retries } = waitingRestorer([4242])
    await next.applyPending()
    await next.snapshot(configPath)
    // The old game exits after the new session's snapshot, before its pid is known.
    running.delete(4242)
    retries.at(-1)?.()
    await next.applyPending()
    expect(existsSync(pendingPath)).toBe(true)
    expect(pendingPids()).toEqual([undefined])
    await next.recordPid(5151)
    expect(pendingPids()).toEqual([5151])
  })

  it('restores con_notifylines and scr_chathud like the stage cvars (story 174 D3)', async () => {
    const kept = 'seta con_notifylines "4"\r\n'
    const before = `// q2pro\r\nset name "Pl\xe4yer"\r\n${kept}set gl_swapinterval "1"\r\n`
    await writeFile(configPath, bytes(before))
    const cvars = createCvarRestore({
      names: [...STAGE_CVAR_NAMES, ...NOTIFY_SESSION_CVARS],
      pendingPath,
    })
    await cvars.snapshot(configPath)
    // The engine wrote the session values on exit; scr_chathud did not exist before.
    await writeFile(
      configPath,
      bytes(
        '// q2pro\r\nset name "Pl\xe4yer"\r\nset con_notifylines "0"\r\nset scr_chathud "0"\r\nset gl_swapinterval "1"\r\n',
      ),
    )
    await cvars.restore()
    const after = (await readBytes()).toString('latin1')
    expect(after).toContain(kept)
    expect(after).not.toContain('scr_chathud')
    expect(after).not.toContain('con_notifylines "0"')
    expect(after.replace(kept, '')).toBe(before.replace(kept, ''))
  })

  it('a pending snapshot never touches a cvar it does not own', async () => {
    await mkdir(join(tmp, 'userData'))
    await writeFile(
      pendingPath,
      JSON.stringify({
        configPath,
        lines: { name: null, vid_fullscreen: 'set vid_fullscreen "1"' },
      }),
    )
    await writeFile(configPath, bytes('set name "a"\nset vid_fullscreen "0"\n'))
    await restorer().applyPending()
    expect((await readBytes()).toString('latin1')).toBe('set name "a"\nset vid_fullscreen "1"\n')
  })

  it('a restore queued before the next snapshot runs first', async () => {
    await writeFile(configPath, bytes('set vid_fullscreen "1"\n'))
    const cvars = restorer()
    await cvars.snapshot(configPath)
    await writeFile(configPath, bytes('set vid_fullscreen "0"\n'))
    // An exit immediately followed by the next stage play: neither awaited before the other starts.
    const restored = cvars.restore()
    const snapped = cvars.snapshot(configPath)
    await Promise.all([restored, snapped])
    await writeFile(configPath, bytes('set vid_fullscreen "0"\n'))
    await cvars.restore()
    expect((await readBytes()).toString('latin1')).toBe('set vid_fullscreen "1"\n')
  })

  it('a failed restore keeps the original snapshot across the next snapshot', async () => {
    const before = 'set vid_fullscreen "1"\nset vid_geometry "1920x1080+0+0"\n'
    await writeFile(configPath, bytes(before))
    let failing = true
    const fs = {
      ...nodeCvarRestoreFs,
      rename: async (from: string, to: string) => {
        if (failing && to === configPath) throw Object.assign(new Error('busy'), { code: 'EBUSY' })
        return nodeCvarRestoreFs.rename(from, to)
      },
    }
    const cvars = createCvarRestore({ names: STAGE_CVAR_NAMES, pendingPath, fs })
    await cvars.snapshot(configPath)
    const staged = 'set vid_fullscreen "0"\nset vid_geometry "640x360+10+20"\n'
    await writeFile(configPath, bytes(staged))
    await expect(cvars.restore()).rejects.toThrow('busy')
    expect(existsSync(pendingPath)).toBe(true)

    // The next play snapshots a config that still holds the stage values - it must not replace the original.
    await cvars.snapshot(configPath)
    expect((await readBytes()).toString('latin1')).toBe(staged)
    failing = false
    await cvars.restore()
    expect((await readBytes()).toString('latin1')).toBe(before)
    expect(existsSync(pendingPath)).toBe(false)
  })

  it("a failed restore of one record does not stop the wait for a running game's record", async () => {
    const deadConfig = join(tmp, 'baseq2', 'dead.cfg')
    await mkdir(join(tmp, 'userData'), { recursive: true })
    const record = (path: string, pid: number) => ({
      configPath: path,
      lines: { vid_fullscreen: 'set vid_fullscreen "1"', vid_geometry: null },
      pid,
    })
    await writeFile(
      pendingPath,
      JSON.stringify([record(deadConfig, 3000), record(configPath, 4242)]),
    )
    await writeFile(deadConfig, bytes('set vid_fullscreen "0"\n'))
    const retries: Array<() => void> = []
    const fs = {
      ...nodeCvarRestoreFs,
      rename: async (from: string, to: string) => {
        if (to === deadConfig) throw Object.assign(new Error('busy'), { code: 'EBUSY' })
        return nodeCvarRestoreFs.rename(from, to)
      },
    }
    const next = createCvarRestore({
      names: STAGE_CVAR_NAMES,
      pendingPath,
      fs,
      isAlive: (pid) => pid === 4242,
      scheduleRetry: (run) => {
        retries.push(run)
        return () => undefined
      },
    })

    await expect(next.applyPending()).rejects.toThrow('busy')
    expect(retries).toHaveLength(1)
  })

  it("the config lives in the game dir, or in Q2PRO's Linux write dir", () => {
    const installation = {
      id: 'q',
      name: 'Q2PRO',
      rootPath: '/games/q2',
      engineKind: 'q2pro' as const,
      gameDirs: ['baseq2'],
    }
    const ctx = (platform: NodeJS.Platform) => ({
      platform,
      homeDir: '/home/u',
      zipDeps: { extractorPath: 'x', extractorExists: false },
    })
    expect(
      sessionConfigPath(installation, 'ctf', join('/games/q2', 'ctf'), ctx('win32'), 'q2pro'),
    ).toBe(join('/games/q2', 'ctf', 'q2config.cfg'))
    expect(
      sessionConfigPath(installation, 'ctf', join('/games/q2', 'ctf'), ctx('linux'), 'q2pro'),
    ).toBe(join('/home/u', '.q2pro', 'ctf', 'q2config.cfg'))
  })

  it('an r1q2 session restores the config r1q2 writes in the game dir, on every platform', () => {
    const installation = {
      id: 'r',
      name: 'R1Q2',
      rootPath: '/games/q2',
      engineKind: 'r1q2' as const,
      gameDirs: ['baseq2'],
    }
    const ctx = (platform: NodeJS.Platform) => ({
      platform,
      homeDir: '/home/u',
      zipDeps: { extractorPath: 'x', extractorExists: false },
    })
    for (const platform of ['win32', 'linux'] as const) {
      expect(
        sessionConfigPath(installation, 'ctf', join('/games/q2', 'ctf'), ctx(platform), 'r1q2'),
      ).toBe(join('/games/q2', 'ctf', limitsFor('r1q2')?.writtenConfigName ?? ''))
    }
  })
})

describe('whole-file session config restore', () => {
  const wholeConfig = (): string => join(tmp, 'baseq2', 'config.cfg')
  const wholeBytes = (): Promise<Buffer> => readFile(wholeConfig())
  // Bytes no text decoding round-trips: CRLF, latin1, a lone CR, NUL and 0xff, no final newline.
  const original = Buffer.concat([
    bytes('// generated by r1q2\r\nset name "Pl\xe4yer"\r\nbind x "say hi"\r'),
    Buffer.from([0x00, 0xff]),
    bytes('\nseta vid_fullscreen 1'),
  ])

  it('a whole-file snapshot puts config.cfg back byte for byte after the game rewrote it', async () => {
    await writeFile(wholeConfig(), original)
    const cvars = restorer()
    await cvars.snapshot(wholeConfig(), { wholeFile: true })
    expect(existsSync(pendingPath)).toBe(true)
    // A demo's stufftext rebound a key and changed an unlisted cvar; the engine archived both.
    await writeFile(wholeConfig(), bytes('bind x "kill"\nset cl_maxfps "999"\n'))
    await cvars.restore()
    expect((await wholeBytes()).equals(original)).toBe(true)
    expect(existsSync(pendingPath)).toBe(false)
  })

  it('a whole-file snapshot of a missing config removes the file the game wrote', async () => {
    const cvars = restorer()
    await cvars.snapshot(wholeConfig(), { wholeFile: true })
    await writeFile(wholeConfig(), bytes('set name "stuffed"\n'))
    await cvars.restore()
    expect(existsSync(wholeConfig())).toBe(false)
    expect(existsSync(pendingPath)).toBe(false)
  })

  it('a pending whole-file snapshot is applied on the next start', async () => {
    await writeFile(wholeConfig(), original)
    // The launcher went away mid-session: the snapshot only exists on disk.
    await restorer().snapshot(wholeConfig(), { wholeFile: true })
    await writeFile(wholeConfig(), bytes('bind x "kill"\n'))
    await restorer().applyPending()
    expect((await wholeBytes()).equals(original)).toBe(true)
    expect(existsSync(pendingPath)).toBe(false)
  })

  it('a pending whole-file snapshot is put back before the next snapshot is taken', async () => {
    await writeFile(wholeConfig(), original)
    await restorer().snapshot(wholeConfig(), { wholeFile: true })
    await writeFile(wholeConfig(), bytes('bind x "kill"\n'))
    // The next session must snapshot the user's file, not the previous session's leftovers.
    const next = restorer()
    await next.snapshot(wholeConfig(), { wholeFile: true })
    expect((await wholeBytes()).equals(original)).toBe(true)
    await writeFile(wholeConfig(), bytes('bind y "kill"\n'))
    await next.restore()
    expect((await wholeBytes()).equals(original)).toBe(true)
  })

  it('restoring an untouched config leaves the file as it was', async () => {
    await writeFile(wholeConfig(), original)
    const cvars = restorer()
    await cvars.snapshot(wholeConfig(), { wholeFile: true })
    await cvars.restore()
    expect((await wholeBytes()).equals(original)).toBe(true)
    expect(existsSync(pendingPath)).toBe(false)
  })

  it('a pending whole-file snapshot with an invalid payload is dropped without touching the config', async () => {
    await writeFile(wholeConfig(), bytes('set name "kept"\n'))
    await mkdir(join(tmp, 'userData'), { recursive: true })
    await writeFile(
      pendingPath,
      JSON.stringify({ configPath: wholeConfig(), lines: {}, file: 'not base64!' }),
    )
    await restorer().applyPending()
    expect((await wholeBytes()).toString('latin1')).toBe('set name "kept"\n')
    expect(existsSync(pendingPath)).toBe(false)
  })
})

describe('reading an archived cvar', () => {
  it('readArchivedCvar takes the last line', async () => {
    await writeFile(
      configPath,
      bytes(
        'seta s_volume "0.2"\r\nset s_volumex "0.9"\r\n  set s_volume 0.45\r\n// set s_volume "1"\r\n',
      ),
    )
    expect(await readArchivedCvar(configPath, 's_volume')).toBe('0.45')
    await writeFile(configPath, 'set name "x"\nseta s_volume "0.6"')
    expect(await readArchivedCvar(configPath, 's_volume')).toBe('0.6')
    await writeFile(configPath, 'set name "x"\n')
    expect(await readArchivedCvar(configPath, 's_volume')).toBeNull()
    expect(await readArchivedCvar(join(tmp, 'missing.cfg'), 's_volume')).toBeNull()
  })
})
